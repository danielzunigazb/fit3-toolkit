"""gen.py: writes the two generated headers hub.c includes, into a directory of your choice (never into the repository):

    icons.h      the 64 x 64 four-bit icons (the size of the stock app-list icons, 2,112 bytes each) of the apps (src/assets/mkicon.py draws them: our own artwork)
    gen_apps.h   HUB_MODE (0: one app owns the window, 1: a list of apps), HOST_MODE (1: each app is a window of its own, opened by the window manager with the stock slide), and the apps' sources included in the order of the list: APPS[] / NAPPS

Used by src/build_firmware.py and by the emulator tests (src/emu/mkimage.py)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(os.path.dirname(HERE), "assets"))
import mkicon

APPS = {"tennis": "app_tennis", "counter": "app_counter", "dice": "app_dice", "mars": "app_mars", "hola": "app_hola"}       # name -> the App symbol in src/watch/apps/<name>.c


def icons_h():
    out = ["/* generated by src/watch/gen.py: do not edit */", "#ifndef F3_ICONS_H", "#define F3_ICONS_H", '#include "ui.h"']
    for name in ("tennis", "counter", "dice", "mars"):
        data = mkicon.encode_indexed4(*mkicon.draw(name, 64)); assert len(data) == 2112
        rows = ",\n".join("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16))
        out.append("H const u8 ICON_%s_DATA[2112] = {\n%s\n};\nH const Icon ICON_%s = { ICON_HDR_I4(64, 64), 2112, ICON_%s_DATA, 0 };" % (name.upper(), rows, name.upper(), name.upper()))
    out.append("#endif")
    return "\n".join(out) + "\n"


def apps_h(apps, hub, install=False, host=False, reply=False, launcher=False):
    for a in apps:
        if a not in APPS: raise SystemExit("unknown app %r (available: %s)" % (a, ", ".join(APPS)))
    if not apps and not (hub and install): raise SystemExit("no apps")
    out = ["/* generated by src/watch/gen.py: do not edit */", "#define HUB_MODE %d" % (1 if hub else 0)]
    if install: out.append("#define F3X_LOADER 1")
    if hub and launcher: out.append("#define LAUNCHER 1")
    out.append("#define HOST_MODE %d" % (1 if hub and host else 0))
    if reply: out += ["#define REPLY_KBD 1", '#define KB_FONT_HEADER "kbfont.h"']
    out += ['#include "apps/%s.c"' % a for a in apps]
    out += ["static const App *const APPS[] = { %s };" % (", ".join("&" + APPS[a] for a in apps) or "0"), "#define NAPPS %d" % len(apps)]
    return "\n".join(out) + "\n"


DISPLAY_CHARS = "0123456789:.- "                                  # the glyphs of the display font: a text set with it must use only these (a missing glyph hangs the display)
DISPLAY_SIZE = 48


def find_display_font():
    """the TTF/OTF of the display digits: $F3_DISPLAY_FONT, or URW Bookman Light found with fc-match (not stored in the repository); None when there is none"""
    import subprocess
    f = os.environ.get("F3_DISPLAY_FONT")
    if f:
        if not os.path.isfile(f): print("warning: F3_DISPLAY_FONT=%s is not a file: the display digits stay Roboto" % f, file=sys.stderr); return None
        return f
    try: f = subprocess.run(["fc-match", "-f", "%{file}", "URW Bookman:light"], capture_output=True, text=True).stdout
    except OSError: return None                                  # no fontconfig on this machine: Roboto
    return f if f and os.path.isfile(f) and "ookman" in os.path.basename(f) else None


def dfont_h(ttf):
    """dfont.h: FT_DISPLAY, the digits font of the hero numbers (the time, the steps, the heart rate); without a font, Roboto 48 as before"""
    if not ttf: return "/* generated by src/watch/gen.py: no display font found, Roboto 48 stays */\n#ifndef F3_DFONT_H\n#define F3_DFONT_H\n#include \"ui.h\"\n#define FT_DISPLAY FT_CLOCK\n#endif\n"
    import mkfont
    return "/* generated by src/watch/gen.py: do not edit */\n#ifndef F3_DFONT_H\n#define F3_DFONT_H\n#include \"ui.h\"\n" + mkfont.emit(mkfont.build(ttf, DISPLAY_SIZE, bpp=2, polish=False, only=DISPLAY_CHARS), "DISPLAY") + "#define FT_DISPLAY (&FONT_DISPLAY)\n#endif\n"


def generate(apps, hub, outdir, install=False, host=False, kb_ttf=None, kb_langs=("en",), launcher=False):
    """kb_ttf: a TTF with Latin glyphs (Roboto Medium): turns on the reply keyboard (kbd.c), its font and the layouts of kb_langs (kblang.py)"""
    os.makedirs(outdir, exist_ok=True)
    if kb_ttf:
        import mkfont
        import kblang
        open(os.path.join(outdir, "kbfont.h"), "w").write(mkfont.emit(mkfont.build(kb_ttf, 24, kblang.alphabet(list(kb_langs)), polish=False), "KB"))
        open(os.path.join(outdir, "kblang.h"), "w").write(kblang.header(list(kb_langs)))
    open(os.path.join(outdir, "dfont.h"), "w").write(dfont_h(find_display_font()))
    open(os.path.join(outdir, "icons.h"), "w").write(icons_h()); open(os.path.join(outdir, "gen_apps.h"), "w").write(apps_h(apps, hub, install, host, bool(kb_ttf), launcher))
    return outdir
